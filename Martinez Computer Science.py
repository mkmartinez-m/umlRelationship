class Rectangle:
    def __init__(self, width, height):
        self.width = width
        self.height = height

    @property
    def width(self):
        return self.__width

    @width.setter
    def width(self, value):
        self.__width = value

    @property
    def height(self):
        return self.__height

    @height.setter
    def height(self, value):
        self.__height = value

    def area(self):
        return self.__width * self.__height



rectangle = Rectangle(10, 5)

print("Width:", rectangle.width)
print("Height:", rectangle.height)

print("Area:", rectangle.area())

rectangle.width = 20
rectangle.height = 10

print("\nAfter changing the dimensions:")
print("Width:", rectangle.width)
print("Height:", rectangle.height)
print("Area:", rectangle.area())

"""Using `@property` makes the code easier to read and understand because it allows us to access and modify private variables like regular attributes instead of calling separate getter and setter methods. It also makes the code shorter and more organized while still protecting the data inside the class."""